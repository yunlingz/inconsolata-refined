import assert from 'node:assert/strict';
import { readFile, writeFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { spawn } from 'node:child_process';
import { join, resolve } from 'node:path';
import { existsSync } from 'node:fs';
import { create } from 'fontkit';
import { PNG } from 'pngjs';
import { root, styles, sources, hintPolicy, glyphGeometryHash, glyphInstructions, sfntTables, sha256, heartbeat } from './lib.mjs';
import { execute, nativeWorkspace, probeFont, outlineTopology } from './native-raster.mjs';
import { modeCandidate, hintFingerprint } from './hinting-candidates.mjs';
import { inkTools } from './ink-profile.mjs';
import { selectionSettings, selectHintMode } from './hint-selection.mjs';
import { hintReviewPage } from './hint-review-page.mjs';
import { outlineSafetyPage } from './outline-safety-page.mjs';
import { calibrateHintBounds } from './hint-bounds.mjs';

const baselineRevision = '2b83b5cca96a41efab1b07d0c74905e429d02dda';
const done = heartbeat('Calibrating generic hint fitting: every glyph, 8–50 px, eight phases, three modes');
const inputsArgument = process.argv.find(arg => arg.startsWith('--inputs='));
const resetSafety = process.argv.includes('--reset-outline-safety');
const limitsFile = join(root, 'reference/outline-native-limits.json');
const temporary = inputsArgument ? resolve(inputsArgument.slice('--inputs='.length)) : await mkdtemp(join(tmpdir(), 'inconsolata-hint-inputs-'));
let native;
try {
  async function prepare() {
    console.log('Preparing stroke-balanced inputs directly from original Inconsolata sources.');
    const builder = spawn(process.execPath, [join(root, 'scripts/build.mjs'), '--hint-inputs=' + temporary], { cwd: root, stdio: ['ignore', 'inherit', 'inherit'] });
    const code = await new Promise((resolve, reject) => { builder.on('error', reject); builder.on('close', resolve); });
    assert.equal(code, 0, 'Original-source calibration input build');
  }
  if (resetSafety) await rm(limitsFile, { force: true });
  if (!existsSync(join(temporary, 'build-info.json')) || resetSafety) await prepare();
  native = await nativeWorkspace();
  const build = JSON.parse((await execute('git', ['show', baselineRevision + ':fonts/build-info.json'])).toString('utf8'));
  let sourceBuild;
  const limits = existsSync(limitsFile) ? JSON.parse(await readFile(limitsFile, 'utf8')) : {
    version: 2, sourceRevision: sources.inconsolata.revision,
    method: 'Generated by the full native geometry acceptance pass. Retain the resized source when no natural/quantized/strong fitting mode preserves resolvable middle-coverage counters and separate ink cores across the threshold sweep. Subpixel features remain scoring diagnostics. These are measured constraints, not hand-authored character exceptions.', styles: {},
  };
  for (;;) {
    sourceBuild = JSON.parse(await readFile(join(temporary, 'build-info.json'), 'utf8'));
    const outlineReview = JSON.parse(await readFile(join(temporary, 'outline-review.json'), 'utf8'));
    let rejected = 0;
    for (const style of styles) {
      console.log(`GEOMETRY SAFETY ${style.name}: every glyph and fitting size`);
      const before = await execute('git', ['show', baselineRevision + ':fonts/InconsolataRefined-' + style.file + '.ttf']);
      const base = await readFile(join(temporary, 'InconsolataRefined-' + style.file + '.ttf')), font = create(base);
      const fonts = {};
      for (const [name, bytes] of Object.entries({ baseline: before, q: base, n: modeCandidate(base, 'n'), s: modeCandidate(base, 's') })) {
        fonts[name] = name + '.ttf'; await writeFile(join(native.directory, fonts[name]), probeFont(bytes, create(bytes)));
      }
      const terminal = new Set(font.characterSet.filter(code => code >= 0x2500 && code <= 0x259f).map(code => font.glyphForCodePoint(code).id));
      const glyphs = Array.from({ length: font.numGlyphs }, (_, id) => {
        const g = font.getGlyph(id);
        return { id, name: g.name, advance: g.advanceWidth,
          bounds: g.path.commands.length ? [g.bbox.minX, g.bbox.minY, g.bbox.maxX, g.bbox.maxY] : null,
          commands: g.path.commands, ...outlineTopology(g), terminal: terminal.has(id) };
      });
      const result = await native.page(`(${outlineSafetyPage.toString()})(${JSON.stringify({ fonts, glyphs, settings: selectionSettings })},${inkTools.toString()})`, 'geometry-' + style.file);
      const names = new Set(result.failures.map(r => r.name));
      console.log(`GEOMETRY SAFETY ${style.name}: ${result.cases} candidate cases; ${names.size} proposals rejected`);
      const records = new Map(outlineReview.results.find(r => r.style === style.name).glyphs.map(g => [g.name, g]));
      for (const name of names) {
        if (!records.get(name)?.strength || limits.styles[style.file]?.[name]) throw new Error(style.name + ' ' + name + ': unresolved native detail regression in retained source geometry');
        (limits.styles[style.file] ??= {})[name] = { rejectedSizes: [...new Set(result.failures.filter(r => r.name === name).map(r => r.size))] };
        rejected++;
      }
    }
    if (!rejected) { await writeFile(limitsFile, JSON.stringify(limits, null, 2) + '\n'); break; }
    await writeFile(limitsFile, JSON.stringify(limits, null, 2) + '\n');
    console.log(`Retaining ${rejected} resized source glyphs after generic native geometry acceptance; rebuilding original-source inputs.`);
    await prepare();
  }
  const policy = { policyVersion: 3, baselineVersion: '1.400', baselineRevision, preservedGlyphCount: 966,
    method: 'All-glyph, per-size selection of natural or quantized stem fitting against the source-balanced outlines. Protect resolvable counters and separate ink cores; score multiscale ink distortion, contrast, phase variation, and subpixel details. Use strong fitting only when neither gentler mode preserves resolvable details. No character-name selection rules. Terminal artwork and appended triangles retain direct rasterization.',
    selection: selectionSettings, previousGeometrySha256: hintPolicy.previousGeometrySha256 ?? hintPolicy.geometrySha256,
    geometrySha256: {}, styles: {} };
  const reports = [], panels = [];
  for (const style of styles) {
    console.log(`HINT REVIEW ${style.name}: all 968 glyphs, 43 sizes × 8 phases × 4 renderings`);
    const bytes = await execute('git', ['show', baselineRevision + ':fonts/InconsolataRefined-' + style.file + '.ttf']);
    const base = await readFile(join(temporary, 'InconsolataRefined-' + style.file + '.ttf'));
    const font = create(base), tables = sfntTables(base), previous = create(bytes);
    const refinement = build.instances.find(i => i.style === style.name).hintRefinement;
    for (let id = 0; id < font.numGlyphs; id++) assert.equal(font.getGlyph(id).name, previous.getGlyph(id).name, 'Original glyph IDs retained');
    policy.geometrySha256[style.file] = glyphGeometryHash(font, policy.preservedGlyphCount);
    const fonts = {};
    for (const [name, candidate] of Object.entries({ baseline: bytes, q: base, n: modeCandidate(base, 'n'), s: modeCandidate(base, 's') })) {
      fonts[name] = name + '.ttf'; fonts[name + 'Text'] = name + '-text.ttf';
      await writeFile(join(native.directory, fonts[name]), probeFont(candidate, create(candidate)));
      await writeFile(join(native.directory, fonts[name + 'Text']), candidate);
    }
    const terminal = new Set(refinement.terminalGlyphs);
    const glyphs = Array.from({ length: font.numGlyphs }, (_, id) => {
      const g = font.getGlyph(id);
      return { id, name: g.name, advance: g.advanceWidth,
        bounds: g.path.commands.length ? [g.bbox.minX, g.bbox.minY, g.bbox.maxX, g.bbox.maxY] : null,
        commands: g.path.commands, ...outlineTopology(g), terminal: terminal.has(g.name), hasInstructions: glyphInstructions(tables, id).length > 0 };
    });
    const data = { style: style.name, settings: selectionSettings, glyphs, fonts };
    const result = await native.page(`(${hintReviewPage.toString()})(${JSON.stringify(data)},${inkTools.toString()},${selectHintMode.toString()})`, 'calibrate-' + style.file);
    assert.deepEqual(result.errors, [], style.name + ': candidate safety');
    panels.push(PNG.sync.read(Buffer.from(result.candidatePng.split(',')[1], 'base64')));
    const selections = {}, counts = { q: 0, n: 0, s: 0 };
    for (const row of result.rows) {
      counts[row.selected]++;
      if (row.selected === 'q') continue;
      const entry = selections[row.name] ??= { id: row.id, n: [], s: [] }, ranges = entry[row.selected], previous = ranges.at(-1);
      if (previous && previous[1] === row.size - 1) previous[1] = row.size;
      else ranges.push([row.size, row.size]);
    }
    policy.styles[style.file] = { baseHintSha256: hintFingerprint(base, policy.preservedGlyphCount), selections };
    const ordinary = result.rows.filter(row => !row.terminal && row.hasInstructions);
    const summary = rows => rows.length ? ({ glyphSizes: rows.length,
      beforeScore: rows.reduce((sum, r) => sum + r.beforeScore, 0) / rows.length,
      afterScore: rows.reduce((sum, r) => sum + r.afterScore, 0) / rows.length,
      improved: rows.filter(r => r.beforeScore - r.afterScore > .005).length,
      worsened: rows.filter(r => r.afterScore - r.beforeScore > .005).length,
      inkRatio: rows.reduce((sum, r) => sum + r.afterSignal, 0) / rows.reduce((sum, r) => sum + r.beforeSignal, 0),
    }) : { glyphSizes: 0, beforeScore: null, afterScore: null, improved: 0, worsened: 0, inkRatio: null };
    const perGlyph = glyphs.map(g => ({ id: g.id, name: g.name, ...summary(ordinary.filter(r => r.id === g.id)) }));
    const report = { style: style.name, baselineSha256: sha256(bytes), sourceInputSha256: sha256(base),
      outlineBalance: sourceBuild.instances.find(instance => instance.style === style.name).outlineBalance,
      baseHintSha256: policy.styles[style.file].baseHintSha256,
      userAgent: result.userAgent, glyphsChecked: glyphs.length, rasterizations: result.rasterizations,
      modes: counts, ...summary(ordinary), bySize: selectionSettings.sizes.map(size => ({ size, ...summary(ordinary.filter(r => r.size === size)) })),
      glyphs: perGlyph, visualRegressionCases: result.rows.filter(r => ['f', 's', 'S'].includes(r.name)) };
    reports.push(report);
    console.log(`HINT REVIEW ${style.name}: score ${report.beforeScore.toFixed(5)} → ${report.afterScore.toFixed(5)}; ${report.improved} improved / ${report.worsened} worsened glyph sizes; ink ${(report.inkRatio * 100).toFixed(2)}% of 1.400`);
  }
  const boundsSafety = await calibrateHintBounds(policy, temporary);
  for (const style of styles) {
    const result = reports.find(row => row.style === style.name);
    result.calibrationBaseHintSha256 = result.baseHintSha256;
    result.baseHintSha256 = policy.styles[style.file].baseHintSha256;
    result.directRasterGlyphs = policy.styles[style.file].directRasterGlyphs;
    result.fittingMetricsStage = 'before final hint-bounds safeguard';
  }
  await writeFile(join(root, 'docs/hint-bounds.json'), JSON.stringify(boundsSafety, null, 2) + '\n');
  const image = new PNG({ width: panels[0].width, height: panels.reduce((sum, panel) => sum + panel.height, 0) });
  let y = 0; for (const panel of panels) { panel.data.copy(image.data, y * image.width * 4); y += panel.height; }
  await writeFile(join(root, 'docs/hinting-candidates.png'), PNG.sync.write(image));
  const policyBytes = Buffer.from(JSON.stringify(policy, null, 2) + '\n');
  await writeFile(join(root, 'reference/hinting.json'), policyBytes);
  await writeFile(join(root, 'docs/hinting-review.json'), JSON.stringify({ baselineVersion: '1.400', baselineRevision,
    method: policy.method, settings: selectionSettings, thresholds: [.35, .5, .65],
    geometryReference: 'Direct quadratic/cubic paths rasterized at 256 px/em, normalized to the ink bounding box. Multiscale 8×8/4×4 ink mass and axis projections plus a density term; mean and worst horizontal phases. These are shape-fidelity proxies, not readability scores.',
    policySha256: sha256(policyBytes), boundsSafety, results: reports }, null, 2) + '\n');
  console.log('Saved the generated hint policy, complete glyph review, and native candidate sheets.');
} finally { if (native) await native.close(); if (!inputsArgument) await rm(temporary, { recursive: true, force: true }); done(); }
